USE gerenciamento_salao_beleza;

SELECT *
FROM CLIENTES;

SELECT *, (PRECO_VENDA - PRECO_COMPRA) AS LUCRO
FROM PRODUTOS
WHERE (PRECO_VENDA - PRECO_COMPRA) > 0
ORDER BY LUCRO DESC;

SELECT 
    NOME_PRODUTO, 
    PRECO_VENDA, 
    DATA_VENDA
FROM PRODUTOS
ORDER BY DATA_VENDA DESC;

SELECT 
    COUNT(*) AS TOTAL_CLIENTES_REGISTRADOS
FROM CLIENTES;

SELECT 
    SUM(PRECO_VENDA - PRECO_COMPRA) AS LUCRO_TOTAL 
FROM PRODUTOS;

SELECT 
    AVG(PRECO_SERVICOS) AS MEDIA_PRECO_SERVICOS
FROM SERVICOS;

SELECT 
    MIN(PRECO_SERVICOS) AS SERVICO_MAIS_BARATO,
    MAX(PRECO_SERVICOS) AS SERVICO_MAIS_CARO
FROM SERVICOS;

SELECT 
    NOME_SERVICO, 
    COUNT(*) AS TOTAL_AGENDAMENTOS
FROM AGENDAMENTO
GROUP BY NOME_SERVICO;

SELECT 
    NOME_SERVICO, 
    COUNT(*) AS TOTAL_AGENDAMENTOS
FROM AGENDAMENTO
GROUP BY NOME_SERVICO
HAVING COUNT(*) > 0;

SELECT 
    NOME_PRODUTO,
    PRECO_COMPRA,
    PRECO_VENDA,
    (PRECO_VENDA - PRECO_COMPRA) AS LUCRO_UNITARIO
FROM PRODUTOS;