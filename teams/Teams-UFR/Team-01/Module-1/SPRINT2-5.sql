CREATE DATABASE IF NOT EXISTS gerenciamento_salao_beleza;
USE gerenciamento_salao_beleza;

CREATE TABLE CLIENTES (
    ID_CLIENTES INT AUTO_INCREMENT PRIMARY KEY,
    CPF VARCHAR(11) UNIQUE NOT NULL,
    NOME TEXT NOT NULL,
    TELEFONE VARCHAR(13) NOT NULL
);

CREATE TABLE SERVICOS (
    NOME_SERVICO VARCHAR(100) PRIMARY KEY,
    PRECO_SERVICOS FLOAT NOT NULL
);

CREATE TABLE COLABORADORES (
    ID_COLABORADOR INT AUTO_INCREMENT PRIMARY KEY,
    NOME_COLABORADOR TEXT NOT NULL,
    ENDEREÇO TEXT NOT NULL,
    TELEFONE VARCHAR(15) NOT NULL
);

CREATE TABLE PRODUTOS (
    ID_PRODUTO INT AUTO_INCREMENT PRIMARY KEY,
    NOME_PRODUTO TEXT NOT NULL,
    PRECO_COMPRA FLOAT NOT NULL,
    PRECO_VENDA FLOAT NOT NULL,
    DATA_COMPRA DATETIME NOT NULL,
    DATA_VENDA DATETIME NOT NULL
);

CREATE TABLE AGENDAMENTO (
    DATA_AGENDAMENTO DATETIME NOT NULL PRIMARY KEY,
    CPF VARCHAR(11) UNIQUE NOT NULL,
    NOME_SERVICO VARCHAR(100),
    CONSTRAINT fk_CPF
        FOREIGN KEY (CPF)
        REFERENCES CLIENTES(CPF),
    CONSTRAINT fk_NOME_SERVICO
        FOREIGN KEY (NOME_SERVICO)
        REFERENCES SERVICOS(NOME_SERVICO)
);